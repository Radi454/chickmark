BroilerTargetCatalogueEntry _entry({
  required String id,
  required String brand,
  required String breed,
  required String? featheringVariant,
  required FlockSexProfile sexProfile,
  required String publicationVersion,
  required String sourceTitle,
  required String sourceUrl,
  required String fcrMethodNote,
  required bool waterFromFeed,
  required String rawRows,
}) {
  final publicationYear = int.tryParse(publicationVersion.substring(0, 4));
  final profile = BroilerTargetProfile(
    id: id,
    brand: brand,
    breed: breed,
    featheringVariant: featheringVariant,
    sexProfile: sexProfile,
    publicationVersion: publicationVersion,
    publicationDate: publicationYear == null
        ? DateTime.utc(2025, 6)
        : DateTime.utc(publicationYear),
    sourceTitle: sourceTitle,
    sourceUrl: sourceUrl,
    isOfficial: true,
    isActive: true,
    syncStatus: 'synced',
  );
  return BroilerTargetCatalogueEntry(
    profile: profile,
    rows: _parseRows(
      profile.id,
      rawRows,
      fcrMethodNote: fcrMethodNote,
      waterFromFeed: waterFromFeed,
    ),
  );
}

List<BroilerTargetRow> _parseRows(
  String profileId,
  String rawRows, {
  required String fcrMethodNote,
  required bool waterFromFeed,
}) {
  return rawRows
      .trim()
      .split('\n')
      .map((line) {
        final values = line.split(',');
        final fcr = _value(values[6]);
        final water = _value(values[7]);
        final notes = <String>[
          if (fcr != null) fcrMethodNote,
          if (waterFromFeed && water != null)
            'Water objective = published daily feed objective × 1.70.',
        ];
        final ageDay = int.parse(values[0]);
        return BroilerTargetRow(
          id: '$profileId-day-$ageDay',
          profileId: profileId,
          ageDay: ageDay,
          bodyWeightG: _value(values[1]),
          dailyGainG: _value(values[2]),
          averageDailyGainG: _value(values[3]),
          dailyFeedIntakeGPerLivingBird: _value(values[4]),
          cumulativeFeedIntakeGPerLivingBird: _value(values[5]),
          fcr: fcr,
          waterMlPerLivingBird: water,
          metricMethodNotes: notes.isEmpty ? null : notes.join(' '),
          syncStatus: 'synced',
        );
      })
      .toList(growable: false);
}

double? _value(String value) {
  if (value.isEmpty) return null;
  return double.parse(value);
}

